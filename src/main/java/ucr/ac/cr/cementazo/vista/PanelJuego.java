@Override
protected void paintComponent(Graphics g){
    super.paintComponent(g);
    if (imagenFondo != null) {
        g.drawImage(imagenFondo, 0, 0, null);
    } else if (fondo != null) {
        fondo.paintIcon(null, g, 0, 0);
    }
    if (controlJuego != null) {
        controlJuego.dibujar(g);
    }
}
